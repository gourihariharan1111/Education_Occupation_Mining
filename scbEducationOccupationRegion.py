def make_rules(data, level):
    # GRANULARITY: cut occupation code to the first `level` digits (1 = coarsest, 4 = finest)
    d = data.assign(occ=data["Yrke2012"].str[:level])
    total = d["count"].sum()
    r = d.groupby([edu_col, "occ"])["count"].sum().reset_index(name="both")
    edu_t = d.groupby(edu_col)["count"].sum()
    occ_t = d.groupby("occ")["count"].sum()
    # ASSOCIATION RULES: confidence and lift, same as before
    r["confidence"] = r["both"] / r[edu_col].map(edu_t)
    r["lift"] = r["confidence"] / (r["occ"].map(occ_t) / total)
    return r

