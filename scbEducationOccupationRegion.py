def fetch_scb(table, params):
    j = requests.get(f"{BASE}/{table}/data", params=params).json()
    dims = j["id"]
    codes = []
    for d in dims:
        idx = j["dimension"][d]["category"]["index"]
        codes.append(sorted(idx, key=idx.get))
    out = pd.DataFrame([dict(zip(dims, c)) for c in product(*codes)])
    assert len(out) == len(j["value"])
    out["count"] = pd.to_numeric(j["value"], errors="coerce")
    for d in dims:
        out[d + "_name"] = out[d].map(j["dimension"][d]["category"]["label"])
    return out

